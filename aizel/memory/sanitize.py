"""Очищает реплики перед записью в память.

Память должна хранить СМЫСЛ, а не оформление терминала. Без фильтра в неё
оседал технический шум: строки вида «(21 слов за 5.8 с)», реплики с приклеенным
префиксом «ты › ». Такой мусор ищется наравне с настоящими воспоминаниями и
затыкает собой выдачу — короткие мусорные строки ещё и получали высокую
важность, потому что содержали слова-триггеры.

Здесь же порог «реплика слишком пуста, чтобы быть воспоминанием»: «ага»,
«ну», «ок» не несут сведений, и хранить их смысла нет.
"""

from __future__ import annotations

import re

# Префиксы, которые приклеиваются к строке оформлением консоли/журнала.
_PREFIXES = ("ты › ", "ты >", "ты:", "ты ›", "Айзель:", "Айзель › ", "Айзель >", "assistant:", "user:")

# Служебные строки интерфейса: «(21 слов за 5.8 с)».
_META_LINE = re.compile(r"^\s*[\(\[]?\s*\d+\s*слов[а-я]*\s+за\s+[\d.,]+\s*с?[\)\]]?\s*$", re.I)

# Реплики, в которых сведений нет вообще.
_EMPTY_REPLIES = frozenset(
    {
        "а", "аг", "ага", "ах", "да", "нет", "ок", "окей", "хорошо", "ясно",
        "ну", "ну ок", "угу", "э", "эх", "ой", "омг", "лол", "ахах", "хах",
        "хз", "неа", "ага?", "??", "...", "…", "!", "?", "жц",
        "привет", "хай", "здарова", "здорово", "пока", "бб", "спс", "спасибо",
        "ладно", "вот", "давай", "сп",
    }
)

# Минимум осмысленных символов, чтобы реплика стала воспоминанием.
_MIN_MEANINGFUL = 4


def clean_reply(text: str) -> str:
    """Срезает оформление терминала, возвращает чистый текст реплики."""
    out = (text or "").strip()
    changed = True
    # Префиксы могут идти подряд («Айзель: ты › ...»), поэтому крутим, пока режут.
    while changed:
        changed = False
        for prefix in _PREFIXES:
            if out.lower().startswith(prefix.lower()):
                out = out[len(prefix) :].strip()
                changed = True
    return out


def is_noise(text: str) -> bool:
    """True, если в реплике нечего помнить."""
    body = clean_reply(text)
    if not body:
        return True
    if _META_LINE.match(body):
        return True
    # Строка из одних знаков препинания/пробелов.
    if not re.search(r"[\w\u0400-\u04FF]", body):
        return True
    compact = re.sub(r"[^\w\u0400-\u04FF]+", " ", body.lower()).strip()
    if compact in _EMPTY_REPLIES:
        return True
    return len(re.sub(r"\s+", "", compact)) < _MIN_MEANINGFUL


def prepare(text: str) -> str | None:
    """Готовит реплику к записи: чистит и отсеивает шум. None — не помнить."""
    body = clean_reply(text)
    if not body or is_noise(body):
        return None
    return body
